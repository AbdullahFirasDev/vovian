#!/usr/bin/env node
// Generates supabase/seed/02_catalog.sql from supabase/seed/catalog.data.mjs.
// IDs are deterministic (md5-based) so tests and fixtures can reference them.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { categories, collections, products, colorsAr } from '../supabase/seed/catalog.data.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const md5 = (s) => createHash('md5').update(s).digest('hex')
export const uuid = (s) => {
  const h = md5(s)
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`
}
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]` : `'{}'::text[]`)
const num = (v) => (v === null || v === undefined ? 'null' : String(v))
const rand = (seed, mod) => parseInt(md5(seed).slice(0, 8), 16) % mod

// Catalogue prices are authored in USD and published in Iraqi dinars at
// ~1,300 IQD/USD, rounded to amounts a boutique would print on a tag.
const IQD_PER_USD = 1300
const toIQD = (usd) => {
  if (usd == null) return null
  const v = usd * IQD_PER_USD
  const step = v >= 100_000 ? 5_000 : 1_000
  return Math.round(v / step) * step
}

const colorCode = (name) => {
  const words = name.split(/\s+/)
  return (words.length > 1 ? words.map((w) => w[0]).join('') : name.slice(0, 3)).toUpperCase()
}
const sizeCode = (s) => (s === 'One Size' ? 'OS' : s)

const out = []
out.push('-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.')
out.push('-- VOVIAN demo catalogue: categories, collections, products, variants, images, inventory.\n')
out.push('begin;\n')

// ── Categories ────────────────────────────────────────────────────────────
out.push('insert into public.categories (id, department, slug, name, translations, image_url, position) values')
out.push(
  categories
    .map(([dept, slug, name, ar, image], i) =>
      `  (${q(uuid(`category:${dept}:${slug}`))}, ${q(dept)}, ${q(slug)}, ${q(name)}, ${j({ ar: { name: ar } })}, ${q(image)}, ${i})`,
    )
    .join(',\n') + ';\n',
)

// ── Collections ───────────────────────────────────────────────────────────
out.push('insert into public.collections (id, slug, name, subtitle, description, translations, cover_image_url, hero_image_url, gallery, is_featured, position) values')
out.push(
  collections
    .map((c) =>
      `  (${q(uuid(`collection:${c.slug}`))}, ${q(c.slug)}, ${q(c.name)}, ${q(c.subtitle)}, ${q(c.description)}, ` +
      `${j({ ar: { name: c.ar, subtitle: c.subtitleAr, description: c.descriptionAr } })}, ${q(c.cover)}, ${q(c.hero)}, ` +
      `${j(c.gallery.map((url) => ({ url, alt: c.name })))}, ${c.featured}, ${c.position})`,
    )
    .join(',\n') + ';\n',
)

// ── Products ──────────────────────────────────────────────────────────────
const now = Date.now()
const day = 86400000
products.forEach((p, idx) => {
  const pid = uuid(`product:${p.slug}`)
  const catId = uuid(`category:${p.dept}:${p.category}`)
  const flags = p.flags ?? {}
  const publishedDaysAgo = flags.new ? 2 + rand(p.slug, 18) : 35 + rand(p.slug, 160)
  const publishedAt = new Date(now - publishedDaysAgo * day).toISOString()
  const sales = flags.best ? 40 + rand(`${p.slug}:s`, 80) : rand(`${p.slug}:s`, 25)
  const translations = {
    ar: {
      name: p.ar.name,
      description: p.ar.description,
      material: p.ar.material,
      care: p.careAr,
    },
  }

  out.push(`-- ${p.name}`)
  out.push(
    'insert into public.products (id, slug, style_code, name, description, material, care, fit, details, translations, department, category_id, ' +
      'price, sale_price, status, is_featured, is_new_arrival, is_best_seller, sales_count, size_guide, tags, published_at, seo_description) values (' +
      [
        q(pid), q(p.slug), q(p.code), q(p.name), q(p.description), q(p.material), q(p.care), q(p.fit), j(p.details ?? []),
        j(translations), q(p.dept), q(catId), num(toIQD(p.price)), num(toIQD(p.sale ?? null)), q('active'),
        !!flags.featured, !!flags.new, !!flags.best, sales, q(p.sizeGuide ?? 'apparel'), arr(p.tags ?? []),
        q(publishedAt), q(p.description.split('. ')[0] + '.'),
      ].join(', ') +
      ');',
  )

  // Options
  const optionRows = []
  p.colors.forEach((c, i) =>
    optionRows.push(`(${q(pid)}, 'color', ${q(c.name)}, ${j({ ar: { label: colorsAr[c.name] ?? c.name } })}, ${q(c.hex)}, ${i})`),
  )
  p.sizes.forEach((s, i) =>
    optionRows.push(`(${q(pid)}, 'size', ${q(s)}, ${j(s === 'One Size' ? { ar: { label: 'مقاس واحد' } } : {})}, null, ${i})`),
  )
  out.push(`insert into public.product_options (product_id, kind, value, translations, swatch_hex, position) values\n  ${optionRows.join(',\n  ')};`)

  // Images (colour-scoped)
  const imageRows = []
  let pos = 0
  p.colors.forEach((c) => {
    c.images.forEach((url) => {
      imageRows.push(
        `(${q(uuid(`image:${p.slug}:${c.name}:${url}`))}, ${q(pid)}, ${q(url)}, ${q(`${p.name} in ${c.name.toLowerCase()}`)}, ${q(p.colors.length > 1 ? c.name : null)}, ${pos++})`,
      )
    })
  })
  out.push(`insert into public.product_images (id, product_id, url, alt, color, position) values\n  ${imageRows.join(',\n  ')};`)

  // Variants
  const variantRows = []
  const stockRows = []
  let vpos = 0
  p.colors.forEach((c) => {
    p.sizes.forEach((s, si) => {
      const sku = `${p.code}-${colorCode(c.name)}-${sizeCode(s)}`
      const vid = uuid(`variant:${sku}`)
      variantRows.push(`(${q(vid)}, ${q(pid)}, ${q(sku)}, ${q(c.name)}, ${q(s)}, ${vpos++})`)
      // Deterministic, realistic stock: middle sizes deeper; a few sold out / low.
      const r = rand(`stock:${sku}`, 100)
      const middle = si > 0 && si < p.sizes.length - 1
      const qty = r < 7 ? 0 : r < 16 ? 1 + (r % 3) : (middle ? 12 : 6) + rand(`q:${sku}`, 18)
      stockRows.push([vid, qty])
    })
  })
  out.push(`insert into public.product_variants (id, product_id, sku, color, size, position) values\n  ${variantRows.join(',\n  ')};`)

  // Inventory rows are created by trigger; set opening stock + movement log.
  out.push(
    `update public.inventory i set on_hand = v.qty from (values\n  ${stockRows
      .map(([id, qty]) => `(${q(id)}::uuid, ${qty})`)
      .join(',\n  ')}\n) as v(id, qty) where i.variant_id = v.id;`,
  )
  out.push(
    `insert into public.inventory_movements (variant_id, delta, quantity_after, reason, note)\n` +
      `select i.variant_id, i.on_hand, i.on_hand, 'initial', 'Opening stock' from public.inventory i\n` +
      `join public.product_variants v on v.id = i.variant_id where v.product_id = ${q(pid)} and i.on_hand > 0;`,
  )

  // Collections
  if (p.collections?.length) {
    out.push(
      `insert into public.product_collections (product_id, collection_id, position) values ${p.collections
        .map((slug) => `(${q(pid)}, ${q(uuid(`collection:${slug}`))}, ${idx})`)
        .join(', ')};`,
    )
  }
  out.push('')
})

// ── Reviews for best sellers ──────────────────────────────────────────────
const reviewers = [
  ['زهراء ح.', 5, 'أجمل من الصور', 'القماش ثقيل وفاخر، والمقاس مطابق تماماً للوصف.'],
  ['مصطفى ع.', 5, 'يستحق السعر', 'ثالث موسم أرتديه وما زال كأنه جديد.'],
  ['شيلان ك.', 4, 'جميل لكن المقاس واسع قليلاً', 'أخذت مقاساً أصغر وكان مثالياً. التوصيل إلى أربيل كان سريعاً.'],
  ['حسين ر.', 5, 'بالضبط ما أردت', 'خياطة نظيفة وجودة عالية بدون شعارات ظاهرة. سأطلب لوناً آخر.'],
  ['رسل س.', 4, 'قطعة رائعة', 'اللون أغنى من الصور، والأكمام أطول قليلاً بالنسبة لي.'],
]
const reviewRows = []
products
  .filter((p) => p.flags?.best)
  .forEach((p) => {
    const n = 2 + rand(`rev:${p.slug}`, 3)
    for (let i = 0; i < n; i++) {
      const [author, rating, title, body] = reviewers[(rand(`${p.slug}:${i}`, 5) + i) % reviewers.length]
      reviewRows.push(
        `(${q(uuid(`product:${p.slug}`))}, ${q(author)}, ${rating}, ${q(title)}, ${q(body)}, true, now() - interval '${5 + rand(`${p.slug}:d${i}`, 60)} days')`,
      )
    }
  })
out.push(`insert into public.reviews (product_id, author_name, rating, title, body, is_approved, created_at) values\n  ${reviewRows.join(',\n  ')};\n`)

out.push('commit;')

writeFileSync(join(root, 'supabase/seed/02_catalog.sql'), out.join('\n') + '\n')
console.log(`Wrote supabase/seed/02_catalog.sql — ${products.length} products, ${categories.length} categories, ${collections.length} collections`)
